#!/usr/bin/env python3
# Rasterise the console menu's typeface (Sorts Mill Goudy, SIL OFL, a revival
# of the Goudy Old Style the arcade's own text is set in) into anti-aliased
# alpha glyphs for src/menufont_data.h. Each size is drawn at 4x and reduced,
# with a stroke that gives the weight of the arcade's lettering.
#   tools/make_menufont.py > src/menufont_data.h      (needs Pillow)
import os
from PIL import Image, ImageDraw, ImageFont

TTF = os.path.join(os.path.dirname(__file__), "fonts", "SortsMillGoudy-Regular.ttf")
SIZES = [("small", 11, 2), ("body", 14, 2), ("big", 20, 3)]   # name, px, stroke at 4x
S = 4

def glyph(font, ch, stroke):
    asc, desc = font.getmetrics()
    w = int(font.getlength(ch)) + 4 * S + 2 * stroke
    h = asc + desc + 2 * stroke + 2 * S
    m = Image.new("L", (w, h))
    ImageDraw.Draw(m).text((2 * S + stroke, S + stroke), ch, font=font, fill=255, stroke_width=stroke, stroke_fill=255)
    W, H = (w + S - 1) // S, (h + S - 1) // S
    big = Image.new("L", (W * S, H * S)); big.paste(m, (0, 0))
    small = big.resize((W, H), Image.BOX)
    return small, (font.getlength(ch) + stroke) / S

print("// Generated by tools/make_menufont.py from Sorts Mill Goudy (SIL Open Font")
print("// Licence 1.1, licences/SortsMillGoudy-OFL.txt). Do not edit.")
print("#pragma once")
print("#include <stdint.h>")
for name, px, stroke in SIZES:
    font = ImageFont.truetype(TTF, px * S)
    data, table = [], []
    gw = gh = 0
    for c in range(32, 127):
        im, adv = glyph(font, chr(c), stroke)
        gw, gh = im.size
        table.append((len(data), im.size[0], round(adv * 4)))   # advance in quarter pixels
        data.extend(im.tobytes())
    print(f"static const uint8_t mf_{name}_px[{len(data)}] = {{")
    for i in range(0, len(data), 32):
        print("    " + ",".join(str(v) for v in data[i:i + 32]) + ",")
    print("};")
    print(f"static const struct {{ uint32_t off; uint8_t w; uint8_t adv4; }} mf_{name}_glyph[95] = {{")
    print("    " + ", ".join(f"{{{o},{w},{a}}}" for o, w, a in table))
    print("};")
    print(f"#define MF_{name.upper()}_H {gh}")
    print(f"#define MF_{name.upper()}_PAD {2}")   # left margin drawn into each glyph, px
