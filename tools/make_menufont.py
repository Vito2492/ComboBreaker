#!/usr/bin/env python3
# Rasterise the console menu's lettering, Press Start 2P (SIL OFL), a blocky
# pixel face like the SNES menus', into alpha glyphs for src/menufont_data.h.
# Each size is drawn at 4x and reduced (8 and 16 px land on whole pixels).
#   tools/make_menufont.py > src/menufont_data.h      (needs Pillow)
import os
from PIL import Image, ImageDraw, ImageFont

FONTS = os.path.join(os.path.dirname(__file__), "fonts")
PIXEL = os.path.join(FONTS, "PressStart2P-Regular.ttf")
SIZES = [("small", PIXEL, 8, 0), ("body", PIXEL, 10, 0), ("big", PIXEL, 16, 0)]   # name, font, px, stroke at 4x
S = 4
FEAT = ["lnum"]     # lining figures, as on the arcade's and the SNES's screens (needs Pillow with raqm)

def glyph(font, ch, stroke):
    asc, desc = font.getmetrics()
    w = int(font.getlength(ch, features=FEAT)) + 4 * S + 2 * stroke
    h = asc + desc + 2 * stroke + 2 * S
    m = Image.new("L", (w, h))
    ImageDraw.Draw(m).text((2 * S + stroke, S + stroke), ch, font=font, fill=255, stroke_width=stroke, stroke_fill=255, features=FEAT)
    W, H = (w + S - 1) // S, (h + S - 1) // S
    big = Image.new("L", (W * S, H * S)); big.paste(m, (0, 0))
    small = big.resize((W, H), Image.BOX)
    return small, (font.getlength(ch, features=FEAT) + stroke) / S

print("// Generated by tools/make_menufont.py from Press Start 2P (SIL Open Font")
print("// Licence 1.1, tools/fonts/OFL-PressStart2P.txt). Do not edit.")
print("#pragma once")
print("#include <stdint.h>")
for name, ttf, px, stroke in SIZES:
    font = ImageFont.truetype(ttf, px * S)
    data, table = [], []
    gw = gh = 0
    for c in range(32, 127):
        im, adv = glyph(font, chr(c), stroke)
        gw, gh = im.size
        table.append((len(data), im.size[0], round(adv * 4)))   # advance in quarter pixels
        data.extend(im.tobytes())
    print(f"static const uint8_t mf_{name}_px[{len(data)}] = {{")
    for i in range(0, len(data), 32):
        print("    " + ",".join(str(v) for v in data[i:i + 32]) + ",")
    print("};")
    print(f"static const struct {{ uint32_t off; uint8_t w; uint8_t adv4; }} mf_{name}_glyph[95] = {{")
    print("    " + ", ".join(f"{{{o},{w},{a}}}" for o, w, a in table))
    print("};")
    print(f"#define MF_{name.upper()}_H {gh}")
    print(f"#define MF_{name.upper()}_PAD {2}")   # left margin drawn into each glyph, px
